"""55: Reproduce exhausted SpaceColonization action and ensure no model call.

All colony mutations must be performed by the already-source-verified
MarkPlanetColonized service, not a parallel model-authored ledger.
"""
from copy import deepcopy
from roblox_mod_ai.code_generator import LuauCodeGenerator
from roblox_mod_ai.generation_scope import generation_scope
from roblox_mod_ai.host_space_colonization import eligible_colony_alias, render_colony_alias
from roblox_mod_ai.luau_analyzer import LuauStaticAnalyzer
from roblox_mod_ai.spec import ModuleKind, RobloxModuleSpec
from tests.test_report41_host_space_actions import fixture

class NoModel:
    def complete(self,*args,**kwargs):
        raise AssertionError("55 colonization must be generated by host, not small model")

def reproduce():
    p=fixture()
    p.requested_prompt="우주모드 자원파밍 이후 다른 행성 식민지화"
    server=RobloxModuleSpec(module_id="dyn_colony55_server",
        name="SpaceColonization52E67D2Server",kind=ModuleKind.SERVER_MODULE,
        file_path="src/server/SpaceColonization52E67D2Server.luau",
        roblox_service="ServerScriptService",
        description="Space craft establishes a colony in space")
    client=RobloxModuleSpec(module_id="dyn_colony55_client",
        name="SpaceColonization52E67D2Client",kind=ModuleKind.CLIENT_SCRIPT,
        file_path="src/client/SpaceColonization52E67D2Client.client.luau",
        roblox_service="StarterPlayer.StarterPlayerScripts",
        description="Generic typed colony form")
    # The production checkpoint includes a persisted PlayerDataManager.
    # A minimal synthetic plan without this server module falsely trips the
    # independent dependency ABI gate before the alias contract is checked.
    persistence = RobloxModuleSpec(module_id="mod_player_data",
        name="PlayerDataManager",kind=ModuleKind.DATA_STORE,
        file_path="src/server/PlayerDataManager.luau",
        roblox_service="ServerScriptService",
        description="Server profile persistence injected in startup registry")
    p.modules.extend([persistence,server,client])
    d=p.game_design["dynamic_design"]
    remote="SpaceColonization52E67D2Action"
    d.setdefault("host_actions",{})[remote]={"service":server.name,"kind":"RemoteFunction","max_args":1}
    d["remotes"][remote]="RemoteFunction"
    d["module_remotes"][server.module_id]=[remote]
    d["module_remotes"][client.module_id]=[remote]
    d["host_typed_actions"][remote]={
        "transport_only":True,"server":server.name,"client":client.name,
        "contract":{"inputs":[{"id":"selection","type":"text"},
                              {"id":"quantity","type":"integer","min":1,"max":10000}],
                    "target":{"kind":"none"},"state_changes":[]}}
    return p,server,client

def test_report55_host_adapter_eliminates_model_exhaustion():
    p,server,client=reproduce()
    assert eligible_colony_alias(server,p) is not None
    assert eligible_colony_alias(client,p) is not None
    generator=LuauCodeGenerator(router=NoModel())
    source=generator.generate_module_code(server,p)
    ui=generator.generate_module_code(client,p)
    assert source==render_colony_alias(server,p)
    assert ui==render_colony_alias(client,p)
    assert 'services[canonicalName]' in source
    assert 'owner.handleAction(player,services,{selection="planet",quantity=1})' in source
    assert 'args.selection~="colony"' in source
    assert 'args.quantity~=1' in source
    assert 'for k in pairs(args) do' in source
    assert 'GetState(player,"RMMInventory")' not in source
    assert 'SetAttribute("Colonized"' not in source
    assert 'Insert(' not in source
    assert 'remote:InvokeServer({selection="colony",quantity=1})' in ui
    assert 'TextBox' not in ui
    scope={r["name"]:r["strategy"] for r in generation_scope(p)["modules"]}
    assert scope[server.name]=="host_space_colony_alias"
    assert scope[client.name]=="host_space_colony_alias"
    assert server.name not in generation_scope(p)["model_action_risk_modules"]

def test_report55_generated_luau_analyzer_rejects_no_host_errors():
    p,server,client=reproduce()
    analyzer=LuauStaticAnalyzer()
    for module in (server,client):
        code=render_colony_alias(module,p)
        errors=[(d.rule,d.message) for d in analyzer.analyze_source(code,module.file_path)
                if d.severity=="ERROR"]
        assert not errors,errors

def test_report55_alias_requires_canonical_verified_owner_and_exact_abi():
    p,server,client=reproduce()
    assert eligible_colony_alias(server,p)
    no_canonical=deepcopy(p)
    no_canonical.modules=[m for m in no_canonical.modules
                          if not m.name.startswith("MarkPlanetColonized")]
    assert eligible_colony_alias(server,no_canonical) is None
    wrong_input=deepcopy(p)
    wrong_input.game_design["dynamic_design"]["host_typed_actions"][
        "SpaceColonization52E67D2Action"]["contract"]["inputs"][0]["id"]="amount"
    assert eligible_colony_alias(server,wrong_input) is None
    wrong_source=deepcopy(p)
    wrong_source.requested_prompt="make a bridge"
    assert eligible_colony_alias(server,wrong_source) is None
    missing_remote=deepcopy(p)
    missing_remote.game_design["dynamic_design"]["remotes"].pop("SpaceColonization52E67D2Action")
    assert eligible_colony_alias(server,missing_remote) is None
